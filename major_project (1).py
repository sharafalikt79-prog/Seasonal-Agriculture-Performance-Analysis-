# Calculate mean values for Profit and Rainfall
season_crop_stats = data.groupby(['Season', 'Crop']).agg({
'Profit_INR': 'mean',
'Rainfall_mm': 'mean',
'Farm_ID': 'count'
}).reset_index().rename(columns={'Farm_ID': 'Frequency'})

fig, axes = plt.subplots(3, 1, figsize=(15, 18))

# Plot 1: Average Profit
sns.barplot(ax=axes[0], x='Crop', y='Profit_INR', hue='Season', data=season_crop_stats)
axes[0].set_title('Average Profit (INR) by Crop and Season')
axes[0].set_ylabel('Avg Profit')

# Plot 2: Average Rainfall
sns.barplot(ax=axes[1], x='Crop', y='Rainfall_mm', hue='Season', data=season_crop_stats)
axes[1].set_title('Average Rainfall (mm) by Crop and Season')
axes[1].set_ylabel('Avg Rainfall')

# Plot 3: Frequency (Count of records)
sns.barplot(ax=axes[2], x='Crop', y='Frequency', hue='Season', data=season_crop_stats)
axes[2].set_title('Frequency of Observations by Crop and Season')
axes[2].set_ylabel('Count')

plt.tight_layout()
plt. show()