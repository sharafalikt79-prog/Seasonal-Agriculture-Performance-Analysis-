g = sns.FacetGrid(data, col="Season", row="Crop", margin_titles=True, height=3, aspect=1.5)
g.map_dataframe(sns.scatterplot, x="Rainfall_mm", y="Production_Tonnes", size="Avg_Temperature_C", alpha=0.6, hue="Avg_Temperature_C", palette="coolwarm")
